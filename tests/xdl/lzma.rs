#[test]
fn decodes_system_xz_stream() {
    assert_eq!(xdl_lzma_decompress(SMALL_XZ).unwrap(), b"hello from xdl");
}

#[test]
fn rejects_truncated_stream() {
    assert_eq!(
        xdl_lzma_decompress(&SMALL_XZ[..SMALL_XZ.len() - 1]),
        Err(LzmaError::Truncated)
    );
}

#[test]
fn grows_output_for_large_decoded_stream() {
    assert_eq!(
        xdl_lzma_decompress(LARGE_XZ).unwrap(),
        vec![0xa5; 128 * 1024]
    );
}

#[test]
fn bounded_decode_rejects_output_growth_past_limit() {
    assert_eq!(
        xdl_lzma_decompress_bounded(LARGE_XZ, 128 * 1024 - 1),
        Err(LzmaError::OutputTooLarge {
            limit: 128 * 1024 - 1,
        })
    );
}

#[test]
fn bounded_decode_accepts_output_exactly_at_limit() {
    assert_eq!(
        xdl_lzma_decompress_bounded(SMALL_XZ, b"hello from xdl".len()).unwrap(),
        b"hello from xdl"
    );
}

#[test]
fn concatenated_streams_are_decoded_in_full() {
    let mut input = SMALL_XZ.to_vec();
    input.extend_from_slice(SMALL_XZ);
    assert_eq!(
        xdl_lzma_decompress(&input).unwrap(),
        b"hello from xdlhello from xdl"
    );
}

#[test]
fn arbitrary_trailing_bytes_are_rejected() {
    let mut input = SMALL_XZ.to_vec();
    input.extend_from_slice(b"trailing");
    assert_eq!(xdl_lzma_decompress(&input), Err(LzmaError::DecodeFailed));
}

#[test]
fn four_zero_padding_bytes_are_accepted() {
    let mut input = SMALL_XZ.to_vec();
    input.extend_from_slice(&[0; 4]);
    assert_eq!(xdl_lzma_decompress(&input).unwrap(), b"hello from xdl");
}

#[test]
fn multiple_four_zero_padding_bytes_are_accepted() {
    let mut input = SMALL_XZ.to_vec();
    input.extend_from_slice(&[0; 8]);
    assert_eq!(xdl_lzma_decompress(&input).unwrap(), b"hello from xdl");
}

#[test]
fn short_zero_padding_is_rejected() {
    let mut input = SMALL_XZ.to_vec();
    input.push(0);
    assert_eq!(xdl_lzma_decompress(&input), Err(LzmaError::Truncated));
}

#[test]
fn concurrent_decodes_are_independent() {
    let compressed = Arc::new(SMALL_XZ.to_vec());
    let handles: Vec<_> = (0..8)
        .map(|_| {
            let compressed = Arc::clone(&compressed);
            thread::spawn(move || {
                assert_eq!(xdl_lzma_decompress(&compressed).unwrap(), b"hello from xdl");
            })
        })
        .collect();
    for handle in handles {
        handle.join().unwrap();
    }
}
